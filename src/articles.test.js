import assert from 'node:assert/strict';
import {articleIn,articlesFor,articleLanguageUrl} from './articles.js';
import {compileArticle} from '../scripts/compile-article.mjs';
const russian={slug:'example',date:'2026-11-12',title:'Статья',description:'Описание',body:'**Текст**',category:'Команда'};
assert.equal(articleIn(russian,'ru'),russian);
assert.equal(articleIn(russian,'en'),null);
assert.deepEqual(articlesFor([russian],'en'),[]);
assert.equal(articleLanguageUrl('/blog/example/','en',[russian]),'/en/blog/');
const translated=compileArticle({...russian,en:{enabled:true,title:'Article',description:'Summary',body:'**English**\n\n<script>alert(1)</script>',category:'Research'}});
assert.equal(articleIn(translated,'en').title,'Article');
assert.equal(articleIn(translated,'en').slug,'example');
assert.equal(articleIn(translated,'en').date,russian.date);
assert.ok(articleIn(translated,'en').html.includes('<strong>English</strong>'));
assert.ok(!articleIn(translated,'en').html.includes('<script>'));
assert.equal(articleLanguageUrl('/blog/example/','en',[translated]),'/en/blog/example/');
assert.equal(articleLanguageUrl('/en/blog/example/','ru',[translated]),'/blog/example/');
const many=Array.from({length:21},(_,i)=>({...russian,slug:'post-'+i}));
assert.equal(articleLanguageUrl('/blog/page/3/','en',many),'/en/blog/');
assert.equal(articleLanguageUrl('/en/blog/','ru',many),'/blog/');
assert.equal(compileArticle({...russian,en:{enabled:false,body:''}}).en.enabled,false);
assert.throws(()=>compileArticle({...russian,en:{enabled:true,title:'',description:'Summary',body:'body'}}),/fill title/);
assert.throws(()=>compileArticle({...russian,en:{enabled:true,title:'Title',description:'Summary',body:' '}}),/fill body/);
assert.equal(compileArticle({...russian,html:'<script>bad</script>'}).html.includes('<script>'),false);
console.log('Manual article translations and language links verified');
